def set_cell(cell, text: str, *, bold: bool = False, center: bool = False) -> None:
    cell.text = ""
    p = cell.paragraphs[0]
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER if center else WD_ALIGN_PARAGRAPH.LEFT
    p.paragraph_format.first_line_indent = Pt(0)
    p.paragraph_format.left_indent = Pt(0)
    p.paragraph_format.space_before = Pt(0)
    p.paragraph_format.space_after = Pt(0)
    r = p.add_run(str(text))
    r.bold = bold
    r.font.name = "等线"
    r._element.rPr.rFonts.set(qn("w:eastAsia"), "等线")
    r.font.size = Pt(9)


def fill_table(table, rows) -> None:
    for ri, row in enumerate(rows):
        if ri >= len(table.rows):
            break
        for ci, value in enumerate(row):
            if ci >= len(table.rows[ri].cells):
                break
            set_cell(table.rows[ri].cells[ci], value, bold=(ri == 0), center=(ri == 0))


def remove_table(table) -> None:
    element = table._element
    element.getparent().remove(element)


def remove_paragraph(paragraph) -> None:
    element = paragraph._element
    element.getparent().remove(element)


def normalize_paragraph(p) -> None:
    p.paragraph_format.first_line_indent = Pt(0)
    p.paragraph_format.left_indent = Pt(0)
    p.paragraph_format.space_before = Pt(0)
    p.paragraph_format.space_after = Pt(3)
    p.paragraph_format.line_spacing = 1.08
    if p.style.name.startswith("Heading"):
        for run in p.runs:
            run.bold = True


